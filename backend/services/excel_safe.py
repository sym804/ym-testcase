"""엑셀 셀에 넣기 전에 수식으로 읽힐 값을 막는다 (CWE-1236).

내보내기가 세 군데(TC 목록, 수행, 리포트)라 한 곳에만 두면 나머지가 뚫린 채로
남는다. 실제로 TC 목록에만 있었다.
"""

#: 엑셀이 수식의 시작으로 읽는 문자. 탭과 줄바꿈은 셀을 밀어내는 데 쓰인다.
#: OWASP 는 = + - @ 와 탭, 캐리지리턴을 든다. 줄바꿈(\n)은 목록에 없지만 같은
#: 계열이고 막아서 잃을 것이 없어 함께 넣는다.
_FORMULA_LEAD = ("=", "+", "-", "@", "\t", "\r", "\n")


def safe_cell(value):
    """위험 문자로 시작하는 문자열에 앞따옴표를 붙여 텍스트로 강제한다.

    값을 지우지 않는다. 앞따옴표는 엑셀이 화면에 보여 주지 않으므로 읽는 사람에게는
    원래 값 그대로다.
    """
    if isinstance(value, str) and value and value[0] in _FORMULA_LEAD:
        return "'" + value
    return value
